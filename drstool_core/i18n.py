def language_tag(choice: str | None, system_language: str = 'en') -> str:
    if not choice or choice.lower() in ('auto', 'automatic'):
        choice = system_language
    return 'tr' if choice.lower().replace('-', '_').split('_')[0] == 'tr' else 'en'


def translate(text: str, language: str = 'en') -> str:
    return TR.get(text, text) if language_tag(language) == 'tr' else text
